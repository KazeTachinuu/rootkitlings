#include <linux/errno.h>
#include <linux/printk.h>
#include <linux/string.h>
#include "aead.h"
#include "selftest.h"
int rk_aead_selftest(void)
{
	static const u8 key[32]={0x92,0xe1,0x1d,0xcd,0xaa,0x86,0x6f,0x5c,0xe7,0x90,0xfd,0x24,0x50,0x1f,0x92,0x50,0x9a,0xac,0xf4,0xcb,0x8b,0x13,0x39,0xd5,0x0c,0x9c,0x12,0x40,0x93,0x5d,0xd0,0x8b};
	static const u8 nonce[12]={0xac,0x93,0xa1,0xa6,0x14,0x52,0x99,0xbd,0xe9,0x02,0xf2,0x1a};
	static const u8 aad[16]={0x1e,0x08,0x89,0x01,0x6f,0x67,0x60,0x1c,0x8e,0xbe,0xa4,0x94,0x3b,0xc2,0x3a,0xd6};
	static const u8 plain[16]={0x2d,0x71,0xbc,0xfa,0x91,0x4e,0x4a,0xc0,0x45,0xb2,0xaa,0x60,0x95,0x5f,0xad,0x24};
	static const u8 expected[32]={0x89,0x95,0xae,0x2e,0x6d,0xf3,0xdb,0xf9,0x6f,0xac,0x7b,0x71,0x37,0xba,0xe6,0x7f,0xec,0xa5,0xaa,0x77,0xd5,0x1d,0x4a,0x0a,0x14,0xd9,0xc5,0x1e,0x1d,0xa4,0x74,0xab};
	u8 sealed[32],opened[16],tampered[32],bad_aad[16]; size_t sl=0,pl=0; int e;
	e=rk_aead_seal(key,nonce,aad,sizeof(aad),plain,sizeof(plain),sealed,sizeof(sealed),&sl);
	if(e||sl!=sizeof(expected)||memcmp(sealed,expected,sizeof(expected))) return e?:-EBADE;
	e=rk_aead_open(key,nonce,aad,sizeof(aad),sealed,sl,opened,sizeof(opened),&pl);
	if(e||pl!=sizeof(plain)||memcmp(opened,plain,sizeof(plain))) return e?:-EBADE;
	memcpy(tampered,sealed,sizeof(tampered)); tampered[31]^=1; memset(opened,0xa5,sizeof(opened)); pl=7;
	e=rk_aead_open(key,nonce,aad,sizeof(aad),tampered,sizeof(tampered),opened,sizeof(opened),&pl);
	if(e!=-EBADMSG||pl!=7||opened[0]!=0xa5) return -EBADE;
	memcpy(bad_aad,aad,sizeof(bad_aad)); bad_aad[0]^=1; memset(opened,0xa6,sizeof(opened)); pl=9;
	e=rk_aead_open(key,nonce,bad_aad,sizeof(bad_aad),sealed,sizeof(sealed),opened,sizeof(opened),&pl);
	if(e!=-EBADMSG||pl!=9||opened[0]!=0xa6) return -EBADE;
	pr_info("rootkitlings: aes-256-gcm nist vector and tamper gate passed\n"); return 0;
}
