static int rk_expect(bool condition, unsigned int *assertions)
{
	(*assertions)++;
	return condition ? 0 : -EINVAL;
}

#define RK_EXPECT(condition) do { \
	if (rk_expect((condition), assertions)) \
		return -EINVAL; \
} while (0)

int rk_sha256_selftest(unsigned int *assertions)
{
	static const size_t lengths[] = { 0, 3, 55, 56, 63, 64, 65 };
	unsigned char candidate[RK_SHA256_DIGEST_SIZE + 1];
	unsigned char altered[RK_SHA256_DIGEST_SIZE];
	unsigned char input[65];
	size_t index;
	bool matches;
	int error;

	if (!assertions)
		return -EINVAL;
	*assertions = 0;
	for (index = 0; index < sizeof(input); index++)
		input[index] = (unsigned char)index;

	for (index = 0; index < ARRAY_SIZE(lengths); index++) {
		const unsigned char *message = input;

		if (index == 1)
			message = (const unsigned char *)"abc";
		memset(candidate, 0xa5, sizeof(candidate));
		error = rk_sha256_digest(message, lengths[index], candidate);
		if (error)
			return error;
		RK_EXPECT(!error);
		RK_EXPECT(!memcmp(candidate, expected[index],
				  RK_SHA256_DIGEST_SIZE));
		RK_EXPECT(candidate[RK_SHA256_DIGEST_SIZE] == 0xa5);
		matches = false;
		RK_EXPECT(!rk_sha256_verify(message, lengths[index],
					 expected[index], &matches) && matches);
		memcpy(altered, expected[index], sizeof(altered));
		altered[index % sizeof(altered)] ^= 0x80;
		matches = true;
		RK_EXPECT(!rk_sha256_verify(message, lengths[index], altered,
					 &matches) && !matches);
	}
	return 0;
}
